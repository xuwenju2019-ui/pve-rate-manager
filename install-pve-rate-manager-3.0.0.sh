#!/bin/bash
# PVE Rate Manager 3.0.0 -- self-contained installer, no manual extraction.
set -euo pipefail
case "${1:-}" in
  '') PRM_ACTION=install ;;
  --check) PRM_ACTION=check ;;
  --uninstall) PRM_ACTION=uninstall ;;
  --help|-h) echo 'Usage: bash install-pve-rate-manager-3.0.0.sh [--check|--uninstall]'; exit 0 ;;
  *) echo 'Unknown argument; use --help.' >&2; exit 2 ;;
esac
[[ $# -le 1 ]] || { echo 'Too many arguments.' >&2; exit 2; }
PRM_SELF=$(readlink -f -- "${BASH_SOURCE[0]}")
python3 - "$PRM_SELF" "$PRM_ACTION" <<'PRM_PY'
import base64,hashlib,io,os,pathlib,subprocess,sys,tarfile,tempfile
data=pathlib.Path(sys.argv[1]).read_bytes()
encoded=data.rsplit(b'\n__PRM_PAYLOAD_V3__\n',1)
if len(encoded)!=2:raise SystemExit('Missing embedded archive; no changes made.')
try:raw=base64.b64decode(b''.join(encoded[1].splitlines()),validate=True)
except Exception:raise SystemExit('Invalid archive encoding; no changes made.')
if hashlib.sha256(raw).hexdigest()!='32d2f5c5c57d07dd63a05645528c1bfcfd6baef2e6a5ce624761237d73aa5d7a':raise SystemExit('Archive checksum mismatch; no changes made.')
files={}
with tarfile.open(fileobj=io.BytesIO(raw),mode='r:gz') as tar:
    members=tar.getmembers()
    if len(members)>256 or sum(m.size for m in members)>16*1024*1024:raise SystemExit('Archive too large.')
    seen=set()
    for member in members:
        p=pathlib.PurePosixPath(member.name)
        if p.is_absolute() or '..' in p.parts or not p.parts or p.parts[0]!='pve-rate-manager':raise SystemExit('Unsafe archive path.')
        if member.name in seen:raise SystemExit('Duplicate archive path.')
        seen.add(member.name)
        if member.isdir():continue
        if not member.isfile() or len(p.parts)<2:raise SystemExit('Unsupported archive member.')
        files[str(pathlib.PurePosixPath(*p.parts[1:]))]=tar.extractfile(member).read()
manifest=files.get('MANIFEST.sha256',b'').decode('utf-8')
expected={}
for line in manifest.splitlines():
    hash_value,name=line.split('  ',1)
    if name in expected:raise SystemExit('Duplicate manifest entry.')
    expected[name]=hash_value
if not expected or set(expected)!=set(files)-{'MANIFEST.sha256'}:raise SystemExit('Manifest file list mismatch.')
for name,hash_value in expected.items():
    if hashlib.sha256(files[name]).hexdigest()!=hash_value:raise SystemExit('File checksum mismatch: '+name)
print('PVE Rate Manager 3.0.0: embedded archive and all files verified.',flush=True)
action=sys.argv[2]
if action=='check':raise SystemExit(0)
if os.geteuid()!=0:raise SystemExit('Run as root on the PVE host.')
with tempfile.TemporaryDirectory(prefix='pve-rate-manager-') as temp:
    folder=pathlib.Path(temp)/'pve-rate-manager'
    for name,content in files.items():
        target=folder.joinpath(*pathlib.PurePosixPath(name).parts)
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_bytes(content)
    result=subprocess.run(['/bin/bash',str(folder/('uninstall.sh' if action=='uninstall' else 'install.sh'))],cwd=folder)
    code=result.returncode
raise SystemExit(code)
PRM_PY
exit $?
